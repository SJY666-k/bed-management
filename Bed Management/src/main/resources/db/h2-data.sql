-- 每个房间 4 张床位：id = (房间 id - 1) * 4 + 床序号
INSERT INTO bed (id, room_no, bed_status, remarks, bed_no)
SELECT (r.id - 1) * 4 + b.n, r.room_no, 1, NULL, CAST(b.n AS VARCHAR(2))
FROM room r
         CROSS JOIN (SELECT 1 AS n
                     UNION ALL
                     SELECT 2
                     UNION ALL
                     SELECT 3
                     UNION ALL
                     SELECT 4) b;

